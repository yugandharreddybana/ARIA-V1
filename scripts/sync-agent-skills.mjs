#!/usr/bin/env node
/** Sync docs/agents/skills ↔ middleware runtime data + embed catalogue.generated.ts */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const docsDir = path.join(root, 'docs/agents/skills');
const dataDir = path.join(root, 'apps/middleware/src/services/agentSkills/data');
const outFile = path.join(root, 'apps/middleware/src/services/agentSkills/catalogue.generated.ts');

fs.mkdirSync(dataDir, { recursive: true });
for (const name of fs.readdirSync(docsDir).filter((n) => n.endsWith('.json'))) {
  fs.copyFileSync(path.join(docsDir, name), path.join(dataDir, name));
}

const base = JSON.parse(fs.readFileSync(path.join(dataDir, '_base.json'), 'utf8'));
const roles = {};
for (const name of fs.readdirSync(dataDir).filter((n) => n.endsWith('.json') && n !== '_base.json')) {
  roles[name.replace(/\.json$/, '')] = JSON.parse(fs.readFileSync(path.join(dataDir, name), 'utf8'));
}

function composeSource() {
  return `
export function composeInstructions(roleKey: string, flowNames: string[] = []): string {
  const base = BASE_SKILL;
  const skill = ROLE_SKILLS[roleKey as EmbeddedRoleKey];
  if (!skill) throw new Error('Missing skill for role ' + roleKey);
  const flows = flowNames.length ? 'Own flows: ' + flowNames.join(', ') + '.' : 'No flow assigned.';
  return [
    'Role: ' + skill.role + ' (' + skill.roleKey + ').',
    'Tier: ' + skill.modelTier + '. Max out: ' + skill.maxOutputTokens + '.',
    'Extends: ' + skill.extends + '.',
    'Inputs: ' + skill.inputs.join('; ') + '.',
    'Do: ' + skill.do.join('; ') + '.',
    "Don't: " + [...skill.dont, ...base.dont].join('; ') + '.',
    'Done-when: ' + skill.doneWhen.join('; ') + '.',
    'HardRules: ' + base.hardRules.map((rule: { id: string }) => rule.id).join(',') + '.',
    'Context: ' + skill.contextLoad.join(',') + '; never ' + base.neverLoad.join(',') + '.',
    flows,
    'Do not merge. User approves every merge and every idea.',
    'Output JSON matching role outputSchema only.',
  ].join('\\n');
}
`.trim();
}

const out = [
  '/* AUTO-GENERATED by scripts/sync-agent-skills.mjs — edit docs/agents/skills then re-run. */',
  `export const BASE_SKILL = ${JSON.stringify(base, null, 2)} as const;`,
  `export const ROLE_SKILLS = ${JSON.stringify(roles, null, 2)} as const;`,
  'export type EmbeddedRoleKey = keyof typeof ROLE_SKILLS;',
  composeSource(),
  '',
].join('\n');

fs.writeFileSync(outFile, out);
console.log('synced', Object.keys(roles).length, 'roles → data/ + catalogue.generated.ts');
